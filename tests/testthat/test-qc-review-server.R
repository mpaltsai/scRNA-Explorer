testthat::test_that("draft, Preview and Apply remain isolated per sample and preserve previous decisions", {
  baselines <- list(A=qc_review_fixture("A"),B=qc_review_fixture("B"))
  server <- function(input,output,session) {
    b<-shiny::reactiveVal(baselines)
    controller<-qc_review_server(input,output,session,function() b())
  }
  shiny::testServer(server,{
    session$setInputs(selectSample="A",qcPreview=0,QCFiltering=0,updateThresholds=0,qcView="preview")
    a_ids<-controller$control_ids()
    t<-qc_default_thresholds(controller$metrics())
    qc_test_set_draft(session,controller,t)
    testthat::expect_null(controller$filtered()$A)
    session$setInputs(qcPreview=1)
    testthat::expect_true(all(controller$preview()$keep))
    testthat::expect_null(controller$filtered()$A)
    testthat::expect_match(output$qcComparisonStatus,"Preview: 4 retained")
    session$setInputs(QCFiltering=1,qcApplyReason="")
    testthat::expect_null(controller$filtered()$A)
    testthat::expect_match(output$QCDataFilt,"Provide a reason")
    session$setInputs(QCFiltering=2,qcApplyReason="Retain the UMI baseline")
    a_revision<-controller$revisions()[["A"]]
    applied_hash<-digest::digest(controller$filtered()$A)
    testthat::expect_identical(colnames(controller$filtered()$A),colnames(baselines$A))
    t$maxUMIsPerCell<-200
    qc_test_set_draft(session,controller,t)
    testthat::expect_null(controller$preview())
    testthat::expect_identical(digest::digest(controller$filtered()$A),applied_hash)
    session$setInputs(QCFiltering=3)
    testthat::expect_match(output$QCDataFilt,"Preview the current thresholds")
    testthat::expect_identical(controller$revisions()[["A"]],a_revision)
    session$setInputs(qcPreview=2)
    testthat::expect_identical(controller$preview()$keep,c(TRUE,TRUE,FALSE,FALSE))
    session$setInputs(selectSample="B")
    testthat::expect_false(identical(a_ids,controller$control_ids()))
    testthat::expect_null(controller$draft())
    session$setInputs(QCFiltering=4)
    testthat::expect_null(controller$filtered()$B)
    tb<-qc_default_thresholds(controller$metrics());qc_test_set_draft(session,controller,tb)
    session$setInputs(qcPreview=3)
    session$setInputs(QCFiltering=5,qcApplyReason="Keep B baseline")
    testthat::expect_identical(digest::digest(controller$filtered()$A),applied_hash)
    testthat::expect_identical(controller$revisions()[["A"]],a_revision)
    b_revision<-controller$revisions()[["B"]]
    testthat::expect_true(nzchar(b_revision))
    testthat::expect_identical(names(controller$require_ready()),c("A","B"))
    session$setInputs(selectSample="A")
    testthat::expect_equal(controller$draft()$maxUMIsPerCell,200)
    testthat::expect_identical(controller$preview()$keep,c(TRUE,TRUE,FALSE,FALSE))
    session$setInputs(QCFiltering=6,qcApplyReason="Accept reviewed A upper limit")
    testthat::expect_equal(ncol(controller$filtered()$A),2)
    testthat::expect_equal(ncol(controller$filtered()$B),4)
    testthat::expect_identical(controller$revisions()[["B"]],b_revision)
    testthat::expect_length(controller$history()$A,2)
    # All plot/table views are tied to the explicit mode, never silently mixed.
    session$setInputs(qcView="applied")
    testthat::expect_identical(levels(controller$comparison()$stage),c("Baseline (UMIs >= 100)","Applied retained"))
    testthat::expect_match(output$qcComparisonStatus,"Applied: 2 retained")
    session$setInputs(qcReviewTab="joint")
    testthat::expect_true(is.list(output$qcJointPlot))
    session$setInputs(qcReviewTab="overview")
    testthat::expect_true(is.list(output$qcSelectedOverview))
    session$setInputs(qcReviewTab="ribosomal")
    testthat::expect_true(is.list(output$qcRibosomalPlot))
    session$setInputs(qcReviewTab="impact")
    testthat::expect_true(is.list(output$qcRuleOverlap))
    testthat::expect_match(output$qcRibosomalCoverage,"median_unresolved_percent")
    # A different unapplied preview must not alter sensitivity in applied mode.
    t$maxUMIsPerCell<-300;qc_test_set_draft(session,controller,t)
    session$setInputs(qcPreview=4)
    testthat::expect_true(all(controller$sensitivity()$current[controller$sensitivity()$rule=="High UMIs"]==200))
    testthat::expect_true(all(controller$sensitivity()$view=="applied"))
    session$setInputs(qcView="preview")
    testthat::expect_true(all(controller$sensitivity()$current[controller$sensitivity()$rule=="High UMIs"]==300))
    testthat::expect_identical(unique(controller$sensitivity()$selection_id),controller$preview()$proposal_id)
    # Invalidating an imported/annotated baseline clears all dependent QC state.
    b(NULL);session$flushReact()
    testthat::expect_null(controller$filtered())
    testthat::expect_null(controller$preview())
    testthat::expect_error(controller$require_ready(),"Create the QC baselines")
  })
})

testthat::test_that("changing one baseline preserves another sample's applied filter and regenerates controls", {
  baselines<-list(A=qc_review_fixture("A"),B=qc_review_fixture("B"))
  server<-function(input,output,session) {
    b<-shiny::reactiveVal(baselines)
    controller<-qc_review_server(input,output,session,function() b())
  }
  shiny::testServer(server,{
    session$setInputs(selectSample="B",qcPreview=0,QCFiltering=0)
    qc_test_set_draft(session,controller,qc_default_thresholds(controller$metrics()))
    session$setInputs(qcPreview=1)
    session$setInputs(QCFiltering=1,qcApplyReason="Keep B")
    hash<-digest::digest(controller$filtered()$B);ids<-controller$control_ids()
    changed<-baselines
    changed$A$qc_nUMI[1]<-101
    b(changed);session$flushReact()
    testthat::expect_identical(digest::digest(controller$filtered()$B),hash)
    testthat::expect_false(identical(controller$control_ids(),ids))
    testthat::expect_null(controller$draft())
    testthat::expect_null(controller$preview())
    session$setInputs(QCFiltering=2)
    testthat::expect_identical(digest::digest(controller$filtered()$B),hash)
  })
})

