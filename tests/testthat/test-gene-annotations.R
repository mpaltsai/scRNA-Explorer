qc_annotation_counts <- function() Matrix::Matrix(matrix(c(9,10,80,0, 10,20,70,0, 0,1,90,10, 0,0,0,0),nrow=4,
  dimnames=list(c("MT-A","HBA","GeneA","Shared"),c("below","boundary","above","zero"))),sparse=TRUE)

testthat::test_that("annotation preserves features and computes the existing metrics", {
  counts <- qc_annotation_counts()
  r <- new_count_import(counts,"A")
  p <- prepare_sample_qc(r,annotation_fixture(),"gene_name")
  testthat::expect_equal(p$metrics$nUMI,c(99,100,101,0))
  testthat::expect_equal(p$metrics$nGene,c(3,3,3,0))
  testthat::expect_equal(p$metrics$mitoRatio,c(9/99,10/100,0,NA))
  testthat::expect_equal(p$metrics$rbcRatio,c(10/99,20/100,1/101,NA))
  testthat::expect_equal(p$metrics$log10GenesPerUMI[1:3],log10(3)/log10(c(99,100,101)))
  testthat::expect_true(is.na(p$metrics$log10GenesPerUMI[4]))
  testthat::expect_identical(p$feature_annotation$annotation_status,c("matched","matched","matched","ambiguous"))
  testthat::expect_true(is.na(p$feature_annotation$gene_id[4]))
  testthat::expect_identical(r$counts,counts)
  testthat::expect_false("counts" %in% names(p))
  b <- make_baseline_sce(r,p)
  testthat::expect_identical(colnames(b),c("boundary","above"))
  testthat::expect_identical(rownames(b),rownames(counts))
  testthat::expect_identical(SummarizedExperiment::assay(b,"counts"),counts[,2:3])
  testthat::expect_equal(baseline_qc_metrics(b)$nUMI,c(100,101))
  testthat::expect_identical(S4Vectors::metadata(b)$scrna_explorer_qc$initial_filter$excluded_cells,c("below","zero"))
})

testthat::test_that("Ensembl lookup uses explicit version handling without renaming rows", {
  counts <- qc_annotation_counts(); rownames(counts) <- paste0("ENSG",1:4,".2")
  r <- new_count_import(counts)
  exact <- prepare_sample_qc(r,annotation_fixture(),"gene_id")
  testthat::expect_true(all(exact$feature_annotation$annotation_status=="unmapped"))
  testthat::expect_true(all(is.na(exact$metrics$mitoRatio)))
  mapped <- prepare_sample_qc(r,annotation_fixture(),"gene_id",TRUE)
  testthat::expect_true(all(mapped$feature_annotation$annotation_status=="matched"))
  b <- make_baseline_sce(r,mapped)
  testthat::expect_identical(rownames(b),rownames(counts))
  testthat::expect_equal(baseline_qc_metrics(b)$mitoRatio,c(.1,0))
  testthat::expect_error(prepare_sample_qc(r,annotation_fixture(),"auto"),"Select gene symbols")
})

testthat::test_that("user-retained duplicate rows contribute separately and survive reimport", {
  counts <- qc_annotation_counts(); rownames(counts) <- c("MT-A","MT-A","HBA","GeneA")
  r <- resolve_import_duplicates(new_count_import(counts),"keep_separate","Keep original rows")
  p <- prepare_sample_qc(r,annotation_fixture(),"gene_name")
  testthat::expect_equal(p$metrics$mtUMI,c(19,30,1,0))
  b <- make_baseline_sce(r,p)
  testthat::expect_identical(rownames(b),rownames(r$counts))
  testthat::expect_identical(SummarizedExperiment::rowData(b)$qc_source_feature_id,rownames(counts))
  # Reimport the saved SCE using the same public import contract, without a file.
  again <- new_count_import(SummarizedExperiment::assay(b,"counts"),feature_data=SummarizedExperiment::rowData(b),
    cell_data=SummarizedExperiment::colData(b),object=b)
  q <- prepare_sample_qc(again,annotation_fixture(),"gene_name")
  testthat::expect_equal(q$metrics$mtUMI,c(30,1))
  testthat::expect_equal(q$metrics$nUMI,c(100,101))
  testthat::expect_identical(rownames(make_baseline_sce(again,q)),rownames(b))
})

testthat::test_that("imported SCE metadata and other assays survive initial filtering", {
  counts <- qc_annotation_counts()
  object <- SingleCellExperiment::SingleCellExperiment(assays=list(counts=counts,other=counts))
  object$nUMI <- rep(999,4); object$sample <- rep("biological_sample",4)
  object$geo_accession <- rep("GSM101",4)
  SummarizedExperiment::rowData(object)$gene_name <- paste0("original",1:4)
  SingleCellExperiment::reducedDim(object,"original") <- matrix(1:8,nrow=4)
  S4Vectors::metadata(object)$geo <- list(source="original",build="hg19")
  r <- new_count_import(counts,"file_group",SummarizedExperiment::rowData(object),SummarizedExperiment::colData(object),object)
  p <- prepare_sample_qc(r,annotation_fixture(),"gene_name")
  b <- make_baseline_sce(r,p)
  testthat::expect_identical(b$nUMI,rep(999,2))
  testthat::expect_identical(b$sample,rep("biological_sample",2))
  testthat::expect_equal(b$qc_nUMI,c(100,101))
  testthat::expect_identical(baseline_qc_metrics(b)$sample,rep("file_group",2))
  testthat::expect_identical(b$geo_accession,rep("GSM101",2))
  testthat::expect_identical(SummarizedExperiment::rowData(b)$gene_name,paste0("original",1:4))
  testthat::expect_identical(SummarizedExperiment::assay(b,"other"),counts[,2:3])
  testthat::expect_identical(SingleCellExperiment::reducedDim(b,"original"),SingleCellExperiment::reducedDim(object,"original")[2:3,])
  testthat::expect_identical(S4Vectors::metadata(b)$geo,S4Vectors::metadata(object)$geo)
  testthat::expect_true(all(c("sample","nUMI") %in% p$legacy_field_conflicts))
  testthat::expect_null(object$qc_nUMI)
  testthat::expect_null(SummarizedExperiment::rowData(object)$qc_gene_id)
  object$qc_nUMI <- rep(1,4)
  r$source_object <- object; r$cell_data <- SummarizedExperiment::colData(object)
  testthat::expect_error(prepare_sample_qc(r,annotation_fixture(),"gene_name"),"reserved QC namespace")
})

testthat::test_that("missing gene-set evidence differs from observed zero expression", {
  counts <- qc_annotation_counts(); counts[1,] <- 0
  p <- prepare_sample_qc(new_count_import(counts),annotation_fixture(),"gene_name")
  testthat::expect_identical(p$summary$mito_status,"available")
  testthat::expect_equal(p$metrics$mitoRatio[1:3],rep(0,3))
  counts <- counts[-1,,drop=FALSE]
  p <- prepare_sample_qc(new_count_import(counts),annotation_fixture(),"gene_name")
  testthat::expect_identical(p$summary$mito_status,"no_matching_features")
  testthat::expect_true(all(is.na(p$metrics$mitoRatio)))
  r <- new_count_import(qc_annotation_counts()[,c(1,4),drop=FALSE])
  b <- make_baseline_sce(r,prepare_sample_qc(r,annotation_fixture(),"gene_name"))
  testthat::expect_identical(dim(b),c(4L,0L))
  testthat::expect_equal(nrow(baseline_qc_metrics(b)),0)
})
